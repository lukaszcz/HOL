#!/usr/bin/env python3
"""Read a pinned source tree and reproduce the patch; never edit that tree.

All outputs are constrained to this script's directory. No build commands.
SOURCE_SHA256.json is intentionally not generated by this script: it is the
reviewed input seal, checked before any transformation.
"""
import argparse
import difflib
import hashlib
import gzip
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_SOURCE = Path(
    "/home/lukasz/.local/opt/Isabelle2025-2/contrib/"
    "polyml-5.9.2-2/src"
)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"expected unique source anchor: {old!r}")
    return text.replace(old, new, 1)


def transformations(originals):
    result = {}
    for name in ("arm64.cpp", "run_time.cpp", "bytecode.cpp", "memmgr.cpp",
                 "processes.cpp"):
        path = "libpolyml/" + name
        raw = originals[path]
        # arm64.cpp is CRLF in the reviewed distribution. Preserve it.
        newline = "\r\n" if b"\r\n" in raw else "\n"
        text = raw.decode().replace("\r\n", "\n")
        anchor = '#include "memmgr.h"' if name == "memmgr.cpp" else (
            '#include "run_time.h"'
        )
        text = replace_once(
            text, anchor, anchor + '\n#include "managed_alloc_counter.h"'
        )
        if name == "arm64.cpp":
            text = replace_once(
                text,
                "        PolyWord* space =\n"
                "            processes->FindAllocationSpace("
                "this, allocWords, true);",
                "        ManagedSetFindCaller(ManagedAllocNative);\n"
                "        PolyWord* space =\n"
                "            processes->FindAllocationSpace("
                "this, allocWords, true);",
            )
            text = replace_once(
                text,
                "        allocPointer -= allocWords; // Now allocate\n",
                "        allocPointer -= allocWords; // Now allocate\n"
                "        RecordManagedAllocation("
                "ManagedAllocNative, allocWords);\n",
            )
            text = replace_once(
                text,
                "    // If we are profiling store allocation we set mem_hl so "
                "that a trap\n"
                "    // will be generated.\n"
                "    if (profileMode == kProfileStoreAllocation)\n"
                "        assemblyInterface.localMbottom = "
                "assemblyInterface.localMpointer;",
                "    // Experimental exact counter: always trap on native "
                "allocation.\n"
                "    // Independent of profileMode and addProfileCount's PC "
                "attribution.\n"
                "    assemblyInterface.localMbottom = "
                "assemblyInterface.localMpointer;",
            )
            # The only place the native backend creates task data for a
            # thread the runtime did not create.
            text = replace_once(
                text,
                "    if (taskData == 0)\n"
                "    {\n"
                "        try {\n"
                "            taskData = processes->CreateNewTaskData();",
                "    if (taskData == 0)\n"
                "    {\n"
                "        RecordManagedForeignThread();\n"
                "        try {\n"
                "            taskData = processes->CreateNewTaskData();",
            )
        elif name == "run_time.cpp":
            impl = (HERE / "counter_impl.inc").read_text()
            text = replace_once(
                text,
                'extern "C" {\n    POLYEXTERNALSYMBOL POLYUNSIGNED PolyFullGC',
                impl + '\nextern "C" {\n'
                '    POLYEXTERNALSYMBOL POLYUNSIGNED PolyFullGC',
            )
            text = replace_once(
                text,
                "    PolyWord *foundSpace = "
                "processes->FindAllocationSpace(taskData, words, false);",
                "    ManagedSetFindCaller(ManagedAllocRTS);\n"
                "    PolyWord *foundSpace = "
                "processes->FindAllocationSpace(taskData, words, false);",
            )
            text = replace_once(
                text,
                "    return pObj;\n}",
                "    RecordManagedAllocation(ManagedAllocRTS,\n"
                "        ManagedHeapReservationWords(words));\n"
                "    return pObj;\n}",
            )
        elif name == "bytecode.cpp":
            text = replace_once(
                text,
                "    PolyWord* space = "
                "processes->FindAllocationSpace(taskData, words, true);",
                "    ManagedSetFindCaller(ManagedAllocInterpreter);\n"
                "    PolyWord* space = "
                "processes->FindAllocationSpace(taskData, words, true);",
            )
            text = replace_once(
                text,
                "        taskData->allocPointer -= words;\n",
                "        taskData->allocPointer -= words;\n"
                "        RecordManagedInterpreterAllocation(false, words);\n",
            )
            text = replace_once(
                text,
                "    if (space == 0) return 0;\n"
                "    return (PolyObject*)(space + 1);",
                "    if (space == 0) return 0;\n"
                "    RecordManagedInterpreterAllocation(true,\n"
                "        ManagedHeapReservationWords(words));\n"
                "    return (PolyObject*)(space + 1);",
            )
        elif name == "processes.cpp":
            text = replace_once(
                text, "    bool triedInterrupt = false;",
                "    bool triedInterrupt = false;\n"
                "    bool managedAfterGC = false;",
            )
            text = replace_once(
                text,
                "            return taskData->allocPointer;\n"
                "        }\n"
                "        else // Insufficient space in this area.",
                "            RecordManagedFindSuccess(ManagedFindSegment, "
                "words,\n"
                "                                     managedAfterGC);\n"
                "            return taskData->allocPointer;\n"
                "        }\n"
                "        else // Insufficient space in this area.",
            )
            text = replace_once(
                text,
                "                if (foundSpace) return foundSpace;",
                "                if (foundSpace)\n"
                "                {\n"
                "                    RecordManagedFindSuccess("
                "ManagedFindLargeObject,\n"
                "                                             words, "
                "managedAfterGC);\n"
                "                    return foundSpace;\n"
                "                }",
            )
            text = replace_once(
                text,
                "#endif\n"
                "                    return taskData->allocPointer;\n"
                "                }\n"
                "            }\n",
                "#endif\n"
                "                    RecordManagedFindSuccess("
                "ManagedFindRefill, words,\n"
                "                                             "
                "managedAfterGC);\n"
                "                    return taskData->allocPointer;\n"
                "                }\n"
                "            }\n",
            )
            text = replace_once(
                text, "                    continue; // Try again",
                "                    managedAfterGC = true; "
                "// Another thread's GC\n"
                "                    continue; // Try again",
            )
            text = replace_once(
                text, "            if (! QuickGC(taskData, words))",
                "            bool managedGC = QuickGC(taskData, words);\n"
                "            RecordManagedQuickGC(managedGC);\n"
                "            if (managedGC) managedAfterGC = true;\n"
                "            if (! managedGC)",
            )
            text = replace_once(
                text,
                "                        if (ProcessAsynchRequests"
                "(taskData))\n"
                "                            return 0; // Has been "
                "interrupted.",
                "                        if (ProcessAsynchRequests"
                "(taskData))\n"
                "                        {\n"
                "                            RecordManagedFindFailure("
                "words);\n"
                "                            return 0; // Has been "
                "interrupted.\n"
                "                        }",
            )
        elif name == "memmgr.cpp":
            text = replace_once(
                text,
                "            if (allocSpace == 0)\n"
                "                return 0; // Try a GC.",
                "            if (allocSpace == 0)\n"
                "            {\n"
                "                RecordManagedCodeFailure();\n"
                "                return 0; // Try a GC.\n"
                "            }",
            )
            text = replace_once(
                text,
                "                            return obj;",
                "                            // Include header and actual "
                "alignment.\n"
                "                            RecordManagedAllocation("
                "ManagedAllocCode,\n"
                "                                (uint64_t)(next - pt));\n"
                "                            return obj;",
            )
        result[path] = text.replace("\n", newline).encode()
    for name in ("Makefile.am", "Makefile.in"):
        path = "libpolyml/" + name
        text = originals[path].decode()
        text = replace_once(
            text, "libpolyml_la_SOURCES = ",
            "noinst_HEADERS += managed_alloc_counter.h\n\n"
            "libpolyml_la_SOURCES = ",
        )
        result[path] = text.encode()
    result["libpolyml/managed_alloc_counter.h"] = (
        HERE / "managed_alloc_counter.h"
    ).read_bytes()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument(
        "--check", action="store_true",
        help="verify the existing artifacts instead of writing them",
    )
    args = parser.parse_args()
    seal = json.loads((HERE / "SOURCE_SHA256.json").read_text())
    canonical = "".join(
        f"{digest}  {name}\n"
        for name, digest in sorted(seal["files"].items())
    ).encode()
    if sha256(canonical) != seal["tree_manifest_sha256"]:
        raise ValueError("input manifest checksum mismatch")
    paths = [p for p in args.source.rglob("*") if p.is_file()]
    actual_names = {p.relative_to(args.source).as_posix() for p in paths}
    if actual_names != set(seal["files"]):
        raise ValueError("source inventory differs from pristine input seal")
    if any(p.is_symlink() for p in paths):
        raise ValueError("source symlinks are not supported")
    originals = {}
    for name, expected in seal["files"].items():
        raw = (args.source / name).read_bytes()
        if sha256(raw) != expected:
            raise ValueError(f"source hash mismatch: {name}")
        originals[name] = raw
    patched = transformations(originals)
    patch = bytearray()
    for name, after in sorted(patched.items()):
        before = originals.get(name, b"")
        patch.extend(b"diff --git a/" + name.encode() + b" b/" +
                     name.encode() + b"\n")
        if name not in originals:
            patch.extend(b"new file mode 100644\n")
        patch.extend(b"".join(difflib.diff_bytes(
            difflib.unified_diff,
            before.splitlines(keepends=True),
            after.splitlines(keepends=True),
            fromfile=("a/" + name).encode() if before else b"/dev/null",
            tofile=("b/" + name).encode(),
        )))
    artifacts = {
        "managed-allocation.patch.gz": gzip.compress(bytes(patch), mtime=0),
        "PATCHED_SHA256.json": (json.dumps(
            {name: sha256(raw) for name, raw in sorted(patched.items())},
            indent=2, sort_keys=True,
        ) + "\n").encode(),
    }
    for name, content in artifacts.items():
        path = HERE / name
        if args.check:
            if path.read_bytes() != content:
                raise ValueError(f"artifact does not reproduce: {name}")
        else:
            path.write_bytes(content)
    print(f"Verified {len(originals)} pinned inputs; "
          f"{'checked' if args.check else 'generated'} "
          f"{len(patched)} patch targets. No build or runtime execution.")


if __name__ == "__main__":
    main()
