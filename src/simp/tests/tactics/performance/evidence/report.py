#!/usr/bin/env python3
"""Regenerate compact per-row analysis from the losslessly archived receipts."""
import json
import math
from pathlib import Path
import statistics
import tarfile

HERE = Path(__file__).resolve().parent


def main():
    with tarfile.open(HERE / "receipts.tar.xz") as archive:
        def load(name):
            return json.load(archive.extractfile(name))
        analysis = load("final-analysis.json")
        minima = {}
        for campaign in ("initial-current", "final-current", "final-control"):
            manifest = load(campaign + "/manifest.json")
            by_key = {}
            for entry in manifest["runs"]:
                name = campaign + "/" + entry["receipt"].removesuffix(".gz")
                receipt = load(name)
                for e in receipt["result"]["observations"]:
                    if e[0] != "observation":
                        continue
                    phase, _, key = e[1].partition(".")
                    if phase not in ("calibration", "batch"):
                        continue
                    fields = e[2].split(",")
                    wall_index = 1 if phase == "calibration" else 2
                    wall = float(fields[wall_index].replace("~", "-"))
                    by_key.setdefault(key, []).append(wall)
            minima[campaign] = by_key
    def inference(section, key, metric):
        row = analysis[section][key][metric]
        return row.get("inference", row)
    def cell(section, key, metric):
        inf = inference(section, key, metric)
        if "family95" not in inf:
            return "Z"
        lo, hi = inf["family95"]["ratio_interval"]
        status = inf["family95"]["decision"]
        return f"{lo:.4f}–{hi:.4f} {'S' if status == 'slower' else 'U'}"
    out = ["# TASK18 per-row observations", "",
        "Generated by `python3 -B evidence/report.py` from archived raw receipts.",
        "All intervals are 95% family intervals (66 workloads per metric).",
        "U = unresolved, S = slower, Z = zero timer/unresolved. **U is not parity.**",
        "CPU = inclusive non-GC + GC CPU, not GC added twice.",
        "Contrast compares independent current/control campaign log ratios;",
        "it does not subtract noise from raw effects or waive slower rows.", ""]
    for campaign, rows in minima.items():
        vals = [v for row in rows.values() for v in row]
        out.append(f"- `{campaign}`: {len(vals)} batches including calibration; "
                   f"wall {min(vals):.6f}–{max(vals):.6f} s.")
    out += ["", "Final CPU geometric-mean ratios span " +
        f"{min(math.exp(inference('candidate', k, 'cpu')['mean_log']) for k in analysis['candidate']):.6f}–" +
        f"{max(math.exp(inference('candidate', k, 'cpu')['mean_log']) for k in analysis['candidate']):.6f}.",
        "All 66 CPU, wall, non-GC, user and system family intervals are unresolved",
        "in current, control and independent contrasts; none establishes parity.",
        "`no_strip_full_complete.0` is individually slower for CPU, wall and",
        "non-GC CPU (CPU ratio 1.013473, individual interval 1.001039–1.026062).",
        "It remains visible despite unresolved family/control contrast intervals.",
        "Seven current GC family intervals are slower; three remain slower in",
        "the independent control contrast. GC has nine zero-timer unresolved rows.",
        "Do not treat source/codegen equality as waiving these GC observations.", "",
        "| Row | CPU current | CPU control | GC current | GC contrast | Min wall current/control (s) |",
        "| --- | --- | --- | --- | --- | --- |"]
    for key in analysis["candidate"]:
        dur = "/".join(f"{min(minima[c][key]):.6f}" for c in
                       ("final-current", "final-control"))
        cells = [cell("candidate", key, "cpu"), cell("control", key, "cpu"),
                 cell("candidate", key, "gc_cpu"), cell("contrast", key, "gc_cpu")]
        out.append("| `" + key + "` | " + " | ".join(cells) + " | " + dur + " |")
    out += ["", "## Slower GC rows: absolute context (not an exemption)", "",
        "Medians of ten process medians, separately for each side. These are",
        "descriptive medians, not paired-effect estimates or cumulative bytes.", "",
        "| Row | GC baseline/candidate (ns/op) | CPU baseline/candidate (us/op) | GC share baseline/candidate |",
        "| --- | --- | --- | --- |"]
    for key, row in analysis["candidate"].items():
        if inference("candidate", key, "gc_cpu").get("family95", {}).get(
                "decision") != "slower":
            continue
        g = [statistics.median(v[i] for v in row["gc_cpu"]["process_medians"])
             for i in (0, 1)]
        c = [statistics.median(v[i] for v in row["cpu"]["process_medians"])
             for i in (0, 1)]
        out.append(f"| `{key}` | {g[0]*1e9:.3f}/{g[1]*1e9:.3f} | "
                   f"{c[0]*1e6:.3f}/{c[1]*1e6:.3f} | "
                   f"{100*g[0]/c[0]:.3f}%/{100*g[1]/c[1]:.3f}% |")
    out += ["", "Complete per-row process medians, all six metrics, paired ratios,",
        "individual/family intervals, independent contrasts and raw sample",
        "durations are in `receipts.tar.xz:final-analysis.json`. All raw",
        "calibrations remain in the process receipts. No outliers were removed.", ""]
    (HERE / "ROWS.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
