#!/usr/bin/env python3
"""Generate all eight focused rows; original 66-row report stays untouched."""
import json
import math
from pathlib import Path
import statistics as st
import tarfile
import sys
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import followup


def point(inference):
    return f"{math.exp(inference['mean_log']):.6f}"


def interval(inference, family=False):
    row = inference['family95' if family else 'individual95']
    a, b = row['ratio_interval']
    return f"[{a:.6f}, {b:.6f}] {row['decision']}"


def main():
    with tarfile.open(HERE / 'receipts.tar.xz') as archive:
        old = json.load(archive.extractfile('final-analysis.json'))
    with followup.recovered() as root:
        diagnostics, new = followup.recheck(root)
        manifests = {c: followup.read(root / c / 'manifest.json')
                     for c in followup.CAMPAIGNS}
        duration = {}
        calibration = {}
        for c in followup.CAMPAIGNS[:2]:
            walls, cals = [], []
            for e in manifests[c]['runs']:
                r = followup.read(root / c / e['receipt'])
                walls += [row['raw'][0] for rows in r['measurements'].values()
                          for row in rows]
                cals += [float(x[2].split(',')[1].replace('~', '-')) for x in
                         r['result']['observations']
                         if x[0] == 'observation' and
                         x[1].startswith('calibration.')]
            duration[c] = [min(walls), st.median(walls), max(walls)]
            calibration[c] = [min(cals), st.median(cals), max(cals)]
        lines = ['# TASK18 focused follow-up rows', '',
                 'Generated by `followup_report.py`. Original all-66-row '
                 '`ROWS.md` and original archives remain unchanged.', '',
                 '95% individual / 66-row-per-metric family Student intervals; '
                 'unresolved is not parity. Independent control contrast is '
                 'not subtracted from raw observations.', '',
                 '## Actual duration seconds (min / median / max)', '']
        for c, v in duration.items():
            lines += [f"- {c} samples: " + ' / '.join(f'{x:.6f}' for x in v) +
                      '; calibration: ' + ' / '.join(
                          f'{x:.6f}' for x in calibration[c])]
        for metric in followup.schema.METRICS:
            lines += ['', '## ' + metric, '',
                '| Key | Original current ratio / individual / family | '
                'Long current ratio / individual / family | '
                'Long control ratio / individual / family | '
                'Independent contrast individual / family |',
                '| --- | --- | --- | --- | --- |']
            for key in new['candidate']:
                cells = [key]
                for r in (old['candidate'], new['candidate'], new['control']):
                    i = r[key][metric]['inference']
                    cells.append(point(i) + ' / ' + interval(i) + ' / ' +
                                 interval(i, True))
                i = new['contrast'][key][metric]
                cells.append(interval(i) + ' / ' + interval(i, True))
                lines.append('| ' + ' | '.join(cells) + ' |')
        lines += ['', '## Separate debug GC/heap diagnostics', '',
                  'Counts cover 2 pairs × 3 samples per side, excluding '
                  'calibration and untimed full GCs. Debug times are not '
                  'timing inference. Live = heap minus free at preceding '
                  'untimed full GC. Nursery sums omit final tails and use '
                  'rounded GC logs: NOT cumulative allocation totals.', '',
                  '| Campaign / key | F/P baseline → candidate | '
                  'Live-byte pair deltas candidate − baseline (batch 0) | '
                  'Nursery capacity MiB baseline / candidate | '
                  'Rounded nursery sum MiB baseline / candidate |',
                  '| --- | --- | --- | --- | --- |']
        for campaign in ('current', 'control'):
            runs = diagnostics[campaign]
            for key in new['candidate']:
                sides = {}
                for side in ('baseline', 'candidate'):
                    rows = [row for name, run in runs.items()
                            if name.endswith('.'+side)
                            for row in run['rows'][key]]
                    caps = [x for row in rows
                            for x in row['capacity_range_mib']]
                    sides[side] = dict(
                        full=sum(x['full_gc'] for x in rows),
                        partial=sum(x['partial_gc'] for x in rows),
                        capacities=[min(caps), max(caps)] if caps else [0, 0],
                        nursery=sum(x['nursery_used_sum_mib'] for x in rows))
                live_deltas = []
                for pair in range(2):
                    live = []
                    for side in ('baseline', 'candidate'):
                        row = runs[f'{pair}.{side}']['rows'][key][0]
                        before = row['before']
                        live.append(before['heap_bytes'] -
                                    before['heap_free_last_full'])
                    live_deltas.append(live[1]-live[0])
                a, b = (sides[s] for s in ('baseline', 'candidate'))
                count = (f"{a['full']}/{a['partial']} → "
                         f"{b['full']}/{b['partial']}")
                capacity = ' / '.join(
                    f"{s['capacities'][0]:.3f}–{s['capacities'][1]:.3f}"
                    for s in (a, b))
                nursery = f"{a['nursery']:.3f} / {b['nursery']:.3f}"
                lines += [f'| {campaign} / {key} | {count} | '
                          f'{live_deltas} | {capacity} | {nursery} |']
        lines += ['', '## Raw pair ratios (all observations retained)', '']
        for key in new['candidate']:
            for metric in ('cpu', 'gc_cpu'):
                for campaign in ('candidate', 'control'):
                    ratios = new[campaign][key][metric]['paired_ratios']
                    lines.append(f'- {key} {metric} {campaign}: ' +
                                 ', '.join(f'{r:.6f}' for r in ratios))
        (HERE / 'FOLLOWUP_ROWS.md').write_text('\n'.join(lines)+'\n')
    print(HERE / 'FOLLOWUP_ROWS.md')


if __name__ == '__main__':
    main()
